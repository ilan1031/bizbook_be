    offline_created_date_with_time: { type: String, default: null },
    offline_created_date_with_time_formatted: { type: String, default: null },
    is_pre_gst: { type: Boolean, default: false },
    account_id: { type: String },
    account_name: { type: String },
    account_type: { type: String },
    account_type_formatted: { type: String, default: null },
    customer_advance_account_id: { type: String, default: null },
    customer_advance_account_name: { type: String, default: null },
    currency_id: { type: String },
    currency_symbol: { type: String },

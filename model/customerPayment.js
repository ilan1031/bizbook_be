    tax_name: { type: String, default: null },
    tax_percentage: { type: Number, default: null },
    tax_type: { type: String, default: null },
    is_advance_payment: { type: Boolean },
    tds_type: { type: String, default: null },
    tds_tax_id: { type: String, default: null },

    // Refund specific fields
    refund_amount: { type: Number, default: null },
    refund_amount_formatted: { type: String, default: null },
    refund_date: { type: Date, default: null },
    refund_date_formatted: { type: String, default: null },
    refund_reason: { type: String, default: null },
    refund_status: { type: String, default: null },


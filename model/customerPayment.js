        invoice_number: { type: String, default: null },
        date: { type: String, default: null },
        date_formatted: { type: String, default: null },
        invoice_amount: { type: Number, default: null },
        amount_applied: { type: Number, default: null },
        amount_applied_formatted: { type: String, default: null },
        tax_amount_withheld_formatted: { type: String, default: null },
        tax_amount_withheld: { type: Number, default: null },
